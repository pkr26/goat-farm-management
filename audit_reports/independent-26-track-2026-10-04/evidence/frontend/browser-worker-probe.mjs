import { chromium } from '../../../../frontend/node_modules/@playwright/test/index.mjs';
import fs from 'node:fs/promises';
const out='audit_reports/independent-26-track-2026-10-04/evidence/frontend';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:390,height:844},timezoneId:'America/Phoenix'});
const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(String(error)));page.on('requestfailed',request=>errors.push(`${request.url()} ${request.failure()?.errorText}`));
const results={};
try{
 await page.goto('http://localhost:3000/worker/login',{waitUntil:'domcontentloaded',timeout:90000});
 await page.getByRole('button',{name:'EN',exact:true}).waitFor({timeout:30000});
 results.freshWorkerLanguage=await page.evaluate(()=>({htmlLang:document.documentElement.lang,stored:localStorage.getItem('herdly.language'),text:document.body.innerText.slice(0,400)}));
 console.log('fresh',JSON.stringify(results.freshWorkerLanguage));
 await page.evaluate(async()=>{await Promise.race([navigator.serviceWorker.ready,new Promise((_,reject)=>setTimeout(()=>reject(new Error('SW ready timeout')),15000))])});
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller,{timeout:30000});
 const readCache=async()=>page.evaluate(async()=>{const cache=await caches.open('herdly-worker-v3');return (await cache.keys()).map(r=>r.url);});
 const before=await readCache();
 await page.getByRole('button',{name:'తెలుగు',exact:true}).click();
 await page.waitForFunction(()=>document.documentElement.lang==='te');
 await page.waitForTimeout(500);
 const after=await readCache();
 results.lazyChunks=after.filter(url=>url.includes('/_next/static/')&&!before.includes(url));
 results.cacheAfterLocale=after;
 // Two real document navigations refresh the same deployment shell.
 await page.reload({waitUntil:'domcontentloaded'});await page.waitForTimeout(500);
 results.cacheAfterNavigation1=await readCache();
 await page.reload({waitUntil:'domcontentloaded'});await page.waitForTimeout(500);
 results.cacheAfterNavigation2=await readCache();
 const cdp=await context.newCDPSession(page);await cdp.send('Network.clearBrowserCache');results.httpCacheClearedBeforeOffline=true;
 await context.setOffline(true);
 await page.reload({waitUntil:'domcontentloaded'});await page.waitForTimeout(2000);
 results.offlineReload=await page.evaluate(()=>({bodyText:document.body.innerText,htmlLang:document.documentElement.lang,busy:document.querySelectorAll('[aria-busy=true]').length,buttons:document.querySelectorAll('button').length}));
 await page.screenshot({path:`${out}/worker-offline-locale-cache-evicted.png`,fullPage:true});
 await context.setOffline(false);
 await page.goto('http://localhost:3000/worker/offline',{waitUntil:'domcontentloaded'});
 await page.waitForTimeout(500);
 results.offlineLandmarks=await page.evaluate(()=>({mains:document.querySelectorAll('main').length,nestedMains:document.querySelectorAll('main main').length}));
 results.errors=errors;
 console.log(JSON.stringify(results,null,2));
 await fs.writeFile(`${out}/browser-worker-probe.json`,JSON.stringify(results,null,2));
}catch(error){console.log('PROBE ERROR',String(error));results.error=String(error);results.errors=errors;results.browserState=await page.evaluate(async()=>({text:document.body.innerText,registrations:(await navigator.serviceWorker.getRegistrations()).map(r=>({scope:r.scope,installing:r.installing?.state,active:r.active?.state}))}));console.log(JSON.stringify(results,null,2));await fs.writeFile(`${out}/browser-worker-probe.json`,JSON.stringify(results,null,2));throw error;}finally{await context.close();await browser.close();}
